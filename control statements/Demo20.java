public class Demo20 {
    public static void main(String[] args) {
        char val = 'A';
        switch (val) {
            case 'A': System.out.println("THALA");
            break;
            case 'D': System.out.println("DHANUSHRAJA");
            break;
            case 'V': System.out.println("JOKER");
            break;
            case 'R': System.out.println("SUPER STARR");
            break;
            default: System.out.println("NO ACTOR AVAIL");
            break;
        }
    }
}
